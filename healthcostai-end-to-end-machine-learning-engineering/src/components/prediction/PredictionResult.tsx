"use client"

import {
  AlertCircle,
  BrainCircuit,
  CheckCircle2,
  Loader2,
} from "lucide-react"

import type { PredictionResponse } from "@/types/prediction"

interface PredictionResultProps {
  result: PredictionResponse | null
  loading?: boolean
  error?: string | null
}

export function PredictionResult({
  result,
  loading = false,
  error = null,
}: PredictionResultProps) {
  if (loading) {
    return (
      <div className="flex min-h-70 flex-col items-center justify-center text-center">
        <div className="flex h-12 w-12 items-center justify-center rounded-xl bg-primary/10">
          <Loader2 className="h-5 w-5 animate-spin text-primary" />
        </div>

        <p className="mt-4 text-sm font-semibold">
          Running inference
        </p>

        <p className="mt-1 max-w-xs text-[11px] leading-5 text-muted-foreground">
          The request is being processed by the deployed machine learning
          pipeline.
        </p>
      </div>
    )
  }

  if (error) {
    return (
      <div className="flex min-h-70 flex-col items-center justify-center text-center">
        <div className="flex h-12 w-12 items-center justify-center rounded-xl bg-destructive/10">
          <AlertCircle className="h-5 w-5 text-destructive" />
        </div>

        <p className="mt-4 text-sm font-semibold">
          Prediction failed
        </p>

        <p className="mt-1 max-w-sm text-[11px] leading-5 text-muted-foreground">
          {error}
        </p>
      </div>
    )
  }

  if (!result) {
    return (
      <div className="flex min-h-70 flex-col items-center justify-center text-center">
        <div className="flex h-12 w-12 items-center justify-center rounded-xl bg-primary/10">
          <BrainCircuit className="h-5 w-5 text-primary" />
        </div>

        <p className="mt-4 text-sm font-semibold">
          Ready for prediction
        </p>

        <p className="mt-1 max-w-xs text-[11px] leading-5 text-muted-foreground">
          Submit the patient information to generate an estimated medical
          insurance charge.
        </p>

        <div className="mt-5 flex items-center gap-1.5 rounded-full border bg-muted/30 px-3 py-1.5">
          <span className="h-1.5 w-1.5 rounded-full bg-primary" />
          <span className="font-mono text-[9px] text-muted-foreground">
            MODEL ONLINE
          </span>
        </div>
      </div>
    )
  }

  return (
    <div className="flex min-h-70 flex-col justify-center">
      <div className="rounded-2xl border border-primary/20 bg-primary/5 p-5">
        <div className="flex items-center gap-2">
          <CheckCircle2 className="h-4 w-4 text-primary" />
          <span className="text-[10px] font-semibold uppercase tracking-[0.14em] text-primary">
            Prediction complete
          </span>
        </div>

        <div className="mt-6">
          <p className="text-[10px] font-medium uppercase tracking-[0.14em] text-muted-foreground">
            Estimated medical charges
          </p>

          <div className="mt-2 flex items-baseline gap-2">
            <span className="text-4xl font-bold tracking-tight text-foreground">
              $
              {result.predicted_charges.toLocaleString("en-US", {
                minimumFractionDigits: 2,
                maximumFractionDigits: 2,
              })}
            </span>
          </div>
        </div>

        <div className="mt-6 border-t border-primary/10 pt-4">
          <p className="text-[10px] leading-5 text-muted-foreground">
            This value is an estimate generated by the trained Random Forest
            regression model and should not be considered a medical or
            financial guarantee.
          </p>
        </div>
      </div>
    </div>
  )
}